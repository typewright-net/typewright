""");
        }
    }

    private static void EmitValueAndConstructor(StringBuilder body, ValueSpec spec)
    {
        var valueExpression = spec.RawIsReference
            ? $"_value ?? throw new global::System.InvalidOperationException(" +
              Literal($"This {spec.Name} was not created through Create or TryCreate (default instance).") + ")"
            : "_value";

