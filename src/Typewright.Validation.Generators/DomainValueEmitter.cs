    }

    private static string ToStringExpression(ValueSpec spec) => spec.ToStringKind switch
    {
        ToStringKind.StringRaw => "_value ?? string.Empty",
        ToStringKind.Temporal => $"_value.ToString(\"O\", {Invariant})",
        ToStringKind.Formattable => $"((global::System.IFormattable)_value).ToString(null, {Invariant})",
        _ => spec.RawIsReference ? "_value?.ToString() ?? string.Empty" : "_value.ToString() ?? string.Empty",
    };

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Indent(string indent, string text)
    {
        if (indent.Length == 0)
        {
            return text;
        }

        var builder = new StringBuilder();
        foreach (var line in text.Split('\n'))
        {
            var trimmed = line.TrimEnd('\r');
            builder.Append(trimmed.Length == 0 ? "" : indent + trimmed).Append('\n');
        }

        return builder.ToString();
    }
