    private static void EmitDomainTypeInfo(StringBuilder body, ValueSpec spec)
    {
        var rules = new StringBuilder();
        if (spec.Pattern is not null)
        {
            rules.Append($"            new {V}.DomainRuleInfo {{ Kind = \"pattern\", Pattern = {Literal(spec.Pattern)} }},\n");
        }

        if (spec.LengthMin is not null && spec.LengthMax is not null)
        {
            rules.Append($"            new {V}.DomainRuleInfo {{ Kind = \"length\", MinLength = {spec.LengthMin}, MaxLength = {spec.LengthMax} }},\n");
        }

        if (spec.HasRange)
        {
            var minimum = spec.RangeMinSchema is null ? "null" : spec.RangeMinSchema + "m";
            var maximum = spec.RangeMaxSchema is null ? "null" : spec.RangeMaxSchema + "m";
            rules.Append($"            new {V}.DomainRuleInfo {{ Kind = \"range\", Minimum = {minimum}, Maximum = {maximum} }},\n");
        }

        if (spec.NotEmpty)
        {
            rules.Append($"            new {V}.DomainRuleInfo {{ Kind = \"not_empty\" }},\n");
        }

        var rulesExpression = rules.Length == 0
            ? $"global::System.Array.Empty<{V}.DomainRuleInfo>()"
            : $"new {V}.DomainRuleInfo[]\n        {{\n{rules}        }}";

        body.Append($$"""
    /// <summary>Reflection-free description of this domain type for schema and OpenAPI use.</summary>
    public static {{V}}.DomainTypeInfo DomainTypeInfo { get; } = new {{V}}.DomainTypeInfo
    {
        Name = {{Literal(spec.Name)}},
        DomainType = typeof({{spec.Name}}),
        RawType = typeof({{spec.RawDisplay}}),
        Rules = {{rulesExpression}},
    };


""");
    }

    private static void EmitTypeConverter(StringBuilder body, ValueSpec spec)
    {
        var name = spec.Name;
        var raw = spec.RawDisplay;

        var fromString = spec.RawIsParsable
            ? $$"""
            if (value is string text)
            {
                return {{name}}.Parse(text, culture ?? {{Invariant}});
            }


"""
            : "";
        var fromRaw = spec.RawIsString
            ? ""
            : $$"""
            if (value is {{raw}} rawValue)
            {
                return {{name}}.Create(rawValue);
            }


""";
        var stringOrRawCheck = spec.RawIsString
            ? "sourceType == typeof(string)"
            : spec.RawIsParsable
                ? $"sourceType == typeof(string) || sourceType == typeof({raw})"
                : $"sourceType == typeof({raw})";
        var toCheck = spec.RawIsString
            ? "destinationType == typeof(string)"
            : $"destinationType == typeof(string) || destinationType == typeof({raw})";
        var toRawBranch = spec.RawIsString
            ? ""
            : $$"""
                if (destinationType == typeof({{raw}}))
                {
                    return domain.Value;
                }


""";

        body.Append($$"""
    /// <summary>Converts from string and raw values for components that still use TypeConverter.</summary>
    public sealed class DomainTypeConverter : global::System.ComponentModel.TypeConverter
    {
        /// <inheritdoc />
        public override bool CanConvertFrom(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Type sourceType)
            => {{stringOrRawCheck}} || base.CanConvertFrom(context, sourceType);

        /// <inheritdoc />
        public override object? ConvertFrom(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Globalization.CultureInfo? culture, object value)
        {
