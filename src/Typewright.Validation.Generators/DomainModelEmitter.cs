using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Typewright.Validation.Generators;

/// <summary>Builds the generated partial for one <see cref="ModelSpec"/>.</summary>
internal static class DomainModelEmitter
{
    private const string V = "global::Typewright.Validation";

    public static string Emit(ModelSpec spec)
    {
        var name = spec.Name;
        var result = $"{V}.ValidationResult<{name}>";
        var builder = new StringBuilder();

        builder.Append("// <auto-generated by Typewright.Validation.Generators />\n#nullable enable\n");

        var indent = "";
        if (spec.Namespace.Length > 0)
        {
            builder.Append($"namespace {spec.Namespace}\n{{\n");
            indent = "    ";
        }

        var body = new StringBuilder();
        body.Append($$"""
[global::System.Text.Json.Serialization.JsonConverter(typeof({{V}}.Json.DomainModelJsonConverter<{{name}}, {{name}}.Dto>))]
[global::System.CodeDom.Compiler.GeneratedCode("Typewright.Validation.Generators", "0.1.0")]
partial record {{name}} : {{V}}.IDomainModel<{{name}}, {{name}}.Dto>
{

""");
        if (spec.HasValidateHook)
        {
            body.Append($$"""
    private {{name}}()
    {
    }


""");
        }

        EmitDto(body, spec);
        EmitTryCreate(body, spec, result);

        body.Append($$"""
    /// <summary>Validates <paramref name="dto"/> and returns the model, or throws <see cref="{{V}}.DomainValidationException"/>.</summary>
    public static {{name}} Create(Dto? dto) => TryCreate(dto).OrThrow();


""");

        if (spec.HasValidateHook)
        {
            EmitTypedFactory(body, spec, result);
        }

        body.Append($$"""
    /// <summary>Optional cross-field rule; runs on a fully field-valid candidate only.</summary>
    static partial void Validate({{name}} candidate, {{V}}.ValidationErrors errors);


""");

        EmitToDto(body, spec);
        EmitDomainTypeInfo(body, spec);

        builder.Append(Indent(indent, body.ToString().TrimEnd('\r', '\n', ' ') + "\n}\n"));
        if (spec.Namespace.Length > 0)
        {
            builder.Append("}\n");
        }

        return builder.ToString();
    }

    private static void EmitDto(StringBuilder body, ModelSpec spec)
    {
        var properties = new StringBuilder();
        foreach (var property in spec.Properties)
        {
            properties.Append($"""
        /// <summary>Raw value for <see cref="{spec.Name}.{property.Name}"/>.</summary>

""");
            if (property.ExplicitJsonName is not null)
            {
                properties.Append($"        [global::System.Text.Json.Serialization.JsonPropertyName({Literal(property.ExplicitJsonName)})]\n");
            }

            properties.Append($"        public {property.DtoTypeDisplay} {property.Name} {{ get; init; }}\n\n");
        }

        body.Append($$"""
    /// <summary>The raw, serialization-friendly shape of a <see cref="{{spec.Name}}"/>: every property is the nullable raw type.</summary>
    public sealed record Dto
    {
{{properties.ToString().TrimEnd('\r', '\n', ' ')}}
    }


""");
    }

    private static void EmitTryCreate(StringBuilder body, ModelSpec spec, string result)
    {
        var blocks = new StringBuilder();
        var assignments = new StringBuilder();

        foreach (var property in spec.Properties)
        {
            var camel = property.CamelName;
            var domain = property.DomainDisplay;
            var json = property.JsonName;

            switch (property.Kind)
            {
                case PropertyKind.Value or PropertyKind.Model when !property.Optional:
                    blocks.Append($$"""
        var {{camel}}Result = {{domain}}.TryCreate(dto.{{property.Name}});
        if (!{{camel}}Result.IsValid)
        {
            errors.Merge({{Literal(json)}}, {{camel}}Result.Errors);
        }


""");
                    assignments.Append($"            {property.Name} = {camel}Result.Value,\n");
                    break;

                case PropertyKind.Value or PropertyKind.Model:
                    blocks.Append($$"""
        {{domain}}? {{camel}}Value = null;
        if (dto.{{property.Name}} is not null)
        {
            var {{camel}}Result = {{domain}}.TryCreate(dto.{{property.Name}});
            if ({{camel}}Result.IsValid)
            {
                {{camel}}Value = {{camel}}Result.Value;
            }
            else
            {
                errors.Merge({{Literal(json)}}, {{camel}}Result.Errors);
            }
        }


""");
                    assignments.Append($"            {property.Name} = {camel}Value,\n");
                    break;

                default:
                {
                    var loop = $$"""
            {{camel}}List = new global::System.Collections.Generic.List<{{domain}}>(dto.{{property.Name}}.Count);
            for (var {{camel}}Index = 0; {{camel}}Index < dto.{{property.Name}}.Count; {{camel}}Index++)
            {
                var {{camel}}ElementResult = {{domain}}.TryCreate(dto.{{property.Name}}[{{camel}}Index]);
                if ({{camel}}ElementResult.IsValid)
                {
                    {{camel}}List.Add({{camel}}ElementResult.Value);
                }
                else
                {
                    errors.Merge({{Literal(json)}} + "[" + {{camel}}Index + "]", {{camel}}ElementResult.Errors);
                }
            }
""";
                    if (property.Optional)
                    {
                        blocks.Append($$"""
        global::System.Collections.Generic.List<{{domain}}>? {{camel}}List = null;
        if (dto.{{property.Name}} is not null)
        {
{{loop}}
        }


""");
                        assignments.Append($"            {property.Name} = {camel}List,\n");
                    }
                    else
                    {
                        blocks.Append($$"""
        global::System.Collections.Generic.List<{{domain}}>? {{camel}}List = null;
        if (dto.{{property.Name}} is null)
        {
            errors.AddAt({{Literal(json)}}, {{V}}.ValidationErrorCodes.Required, "A value is required.");
        }
        else
        {
{{loop}}
        }


""");
                        assignments.Append($"            {property.Name} = {camel}List!,\n");
                    }

                    break;
                }
            }
        }

        body.Append($$"""
    /// <summary>
    /// Validates <paramref name="dto"/> and returns the model or all failures, accumulated
    /// across every property before any cross-field rule runs. Never throws.
    /// </summary>
    public static {{result}} TryCreate(Dto? dto)
    {
        if (dto is null)
        {
            return {{result}}.Failure(string.Empty, {{V}}.ValidationErrorCodes.Required, "A value is required.");
        }

        var errors = new {{V}}.ValidationErrors();

{{blocks}}        if (errors.Count > 0)
        {
            return {{result}}.Failure(errors);
        }

        var __instance = new {{spec.Name}}
        {
{{assignments.ToString().TrimEnd('\r', '\n', ',').TrimEnd(',')}},
        };

        Validate(__instance, errors);
        return errors.Count > 0
            ? {{result}}.Failure(errors)
            : {{result}}.Success(__instance);
    }


""");
    }

    private static void EmitTypedFactory(StringBuilder body, ModelSpec spec, string result)
    {
        var parameters = string.Join(", ", spec.Properties.Select(property =>
            $"{property.DeclaredDisplay}{(property.Optional ? "?" : "")} {property.CamelName}"));
        var arguments = string.Join(", ", spec.Properties.Select(property => property.CamelName));
        var assignments = new StringBuilder();
        foreach (var property in spec.Properties)
        {
            assignments.Append($"            {property.Name} = {property.CamelName},\n");
        }

        body.Append($$"""
    /// <summary>Builds the model from already-valid fields, running the cross-field rule. Never throws.</summary>
    public static {{result}} TryCreate({{parameters}})
    {
        var __candidate = new {{spec.Name}}
        {
{{assignments.ToString().TrimEnd('\r', '\n', ',').TrimEnd(',')}},
        };

        var __errors = new {{V}}.ValidationErrors();
        Validate(__candidate, __errors);
        return __errors.Count > 0
            ? {{result}}.Failure(__errors)
            : {{result}}.Success(__candidate);
    }

    /// <summary>Builds the model from already-valid fields, throwing when the cross-field rule fails.</summary>
    public static {{spec.Name}} Create({{parameters}}) => TryCreate({{arguments}}).OrThrow();


""");
    }

    private static void EmitToDto(StringBuilder body, ModelSpec spec)
    {
        var assignments = new StringBuilder();
        foreach (var property in spec.Properties)
        {
            var expression = property.Kind switch
            {
                PropertyKind.Value => property.Optional
                    ? $"this.{property.Name}?.Value"
                    : $"this.{property.Name}.Value",
                PropertyKind.Model => property.Optional
                    ? $"this.{property.Name}?.ToDto()"
                    : $"this.{property.Name}.ToDto()",
                PropertyKind.ValueCollection => Collection(property, $"({property.RawOrDtoDisplay}?)item.Value"),
                _ => Collection(property, $"({property.RawOrDtoDisplay}?)item.ToDto()"),
            };
            assignments.Append($"        {property.Name} = {expression},\n");
        }

        body.Append($$"""
    /// <summary>Converts the model back to its raw DTO shape.</summary>
    public Dto ToDto() => new Dto
    {
{{assignments.ToString().TrimEnd('\r', '\n', ',').TrimEnd(',')}},
    };


""");

        static string Collection(PropertySpec property, string projection)
        {
            var convert = "global::System.Linq.Enumerable.ToList(global::System.Linq.Enumerable.Select("
                + $"this.{property.Name}, static item => {projection}))";
            return property.Optional
                ? $"this.{property.Name} is null ? null : {convert}"
                : convert;
        }
    }

    private static void EmitDomainTypeInfo(StringBuilder body, ModelSpec spec)
    {
        var fields = new StringBuilder();
        foreach (var property in spec.Properties)
        {
            var isCollection = property.Kind is PropertyKind.ValueCollection or PropertyKind.ModelCollection;
            fields.Append(
                $"            new {V}.DomainFieldInfo {{ Name = {Literal(property.JsonName)}, " +
                $"PropertyName = {Literal(property.Name)}, FieldType = typeof({property.DomainDisplay}), " +
                $"Required = {(property.Optional ? "false" : "true")}, " +
                $"IsCollection = {(isCollection ? "true" : "false")} }},\n");
        }

        var fieldsExpression = fields.Length == 0
            ? $"global::System.Array.Empty<{V}.DomainFieldInfo>()"
            : $"new {V}.DomainFieldInfo[]\n        {{\n{fields}        }}";

        body.Append($$"""
    /// <summary>Reflection-free description of this domain type for schema and OpenAPI use.</summary>
    public static {{V}}.DomainTypeInfo DomainTypeInfo { get; } = new {{V}}.DomainTypeInfo
    {
        Name = {{Literal(spec.Name)}},
        DomainType = typeof({{spec.Name}}),
        RawType = typeof(Dto),
        Fields = {{fieldsExpression}},
    };


""");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Indent(string indent, string text)
    {
        if (indent.Length == 0)
        {
            return text;
        }

        var builder = new StringBuilder();
        foreach (var line in text.Split('\n'))
        {
            var trimmed = line.TrimEnd('\r');
            builder.Append(trimmed.Length == 0 ? "" : indent + trimmed).Append('\n');
        }

        return builder.ToString();
    }
}
