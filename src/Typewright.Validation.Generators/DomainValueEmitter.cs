    private static void EmitTryCreate(StringBuilder body, ValueSpec spec, string result)
    {
        var name = spec.Name;
        var raw = spec.RawDisplay;
        var rules = new StringBuilder();

        if (spec.RawIsString)
        {
            if (spec.NormalizeTrim)
            {
                rules.Append("        value = value.Trim();\n");
            }

            if (spec.NormalizeCase == 1)
            {
                rules.Append("        value = value.ToUpperInvariant();\n");
            }
            else if (spec.NormalizeCase == 2)
            {
                rules.Append("        value = value.ToLowerInvariant();\n");
            }

            if (rules.Length > 0)
            {
                rules.Append('\n');
            }

            if (spec.Pattern is not null)
            {
                rules.Append($$"""
        if (!s_pattern.IsMatch(value))
        {
            errors.Add({{V}}.ValidationErrorCodes.Pattern, {{Literal($"The value must match the pattern '{spec.Pattern}'.")}});
        }


""");
            }

            if (spec.LengthMin is not null && spec.LengthMax is not null)
            {
                rules.Append($$"""
        if (value.Length is < {{spec.LengthMin}} or > {{spec.LengthMax}})
        {
            errors.Add({{V}}.ValidationErrorCodes.Length, {{Literal($"The value must be between {spec.LengthMin} and {spec.LengthMax} characters long.")}});
        }


""");
            }

            if (spec.NotEmpty)
            {
                rules.Append($$"""
        if (string.IsNullOrWhiteSpace(value))
        {
            errors.Add({{V}}.ValidationErrorCodes.NotEmpty, "The value must not be blank.");
        }


""");
            }
        }
        else if (spec.HasRange)
        {
            rules.Append($$"""
        if (value.CompareTo({{spec.RangeMinExpr}}) < 0 || value.CompareTo({{spec.RangeMaxExpr}}) > 0)
        {
            errors.Add({{V}}.ValidationErrorCodes.Range, {{Literal($"The value must be between {spec.RangeMinDisplay} and {spec.RangeMaxDisplay}.")}});
        }


""");
        }

        if (spec.RawIsReference)
        {
            // Reference raw (string included): a single nullable-input TryCreate.
            body.Append($$"""
    /// <summary>Validates <paramref name="value"/> and returns the value or all failures. Never throws.</summary>
    public static {{result}} TryCreate({{raw}}? value)
    {
        var errors = new {{V}}.ValidationErrors();
        if (value is null)
        {
            errors.Add({{V}}.ValidationErrorCodes.Required, "A value is required.");
            return {{result}}.Failure(errors);
        }

{{rules}}        if (errors.Count == 0)
        {
            Validate(value, errors);
        }

        return errors.Count > 0
            ? {{result}}.Failure(errors)
            : {{result}}.Success(new {{spec.Name}}(value));
    }

    /// <summary>Validates <paramref name="value"/> and returns the value, or throws <see cref="{{V}}.DomainValidationException"/>.</summary>
    public static {{spec.Name}} Create({{raw}}? value) => TryCreate(value).OrThrow();


""");
        }
        else
        {
            // Value raw: the plain overload implements the contract; the nullable overload
            // lets nullable DTO properties bind directly.
            body.Append($$"""
    /// <summary>Validates <paramref name="value"/> and returns the value or all failures. Never throws.</summary>
    public static {{result}} TryCreate({{raw}} value)
    {
